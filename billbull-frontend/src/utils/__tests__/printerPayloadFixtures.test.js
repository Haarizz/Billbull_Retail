const built = {};

beforeAll(async () => {
  vi.useFakeTimers({ toFake: ['Date'] });
  vi.setSystemTime(new Date('2026-07-04T04:00:00Z'));
  vi.spyOn(console, 'log').mockImplementation(() => {}); // zebraZpl layout diagnostics
  vi.spyOn(console, 'warn').mockImplementation(() => {});
  for (const [name, p] of Object.entries(PAYLOADS)) built[name] = Uint8Array.from(await p.build());
});

afterAll(() => {
  vi.useRealTimers();
  vi.restoreAllMocks();
});

describe('real printer payloads vs the command policies', () => {
  for (const [name, { protocol }] of Object.entries(PAYLOADS)) {
    it(`${name} passes the ${protocol} policy`, () => {
      const bytes = built[name];
      const own = protocol === 'zpl' ? inspectZpl : inspectEscPos;
      expect(own(bytes)).toEqual({ allowed: true });
      if (protocol === 'escpos') expect(inspectZpl(bytes).allowed).toBe(false);
    });
  }

  it('hostile label text is printed, never executed', () => {
    const zpl = new TextDecoder().decode(built['zpl-product-hostile-text.zpl']);
    expect(zpl).not.toContain('~');
    expect(zpl).toContain('^FH^FDShirt_5EJUF_7EJR_5EXZ_5EXA^FS');
    expect(zpl).toContain('^FDAli_5FBaba\\\\Co^FS');            // ^FB field: backslash doubled
    expect(zpl).toContain('^FH^FDAB_5EC_7ED_5FE^FS');           // barcode: no ^FB, no doubling
    expect(zpl).toContain('Code: A B C');                      // control characters → spaces
    expect(zpl.match(/\^XA/g)).toHaveLength(1);
  });

  it('the raster really does contain the command look-alikes', () => {
    const hex = Buffer.from(built['escpos-canvas-raster.bin']).toString('hex');
    expect(hex).toContain('1b700019fa5e58417e4a52');
  });
});

describe('pinned fixture files (consumed by the backend and the agent)', () => {
  it('match what the builders produce today', () => {
    const manifest = Object.entries(PAYLOADS).map(([file, { protocol, source }]) => ({ file, protocol, source }));
    if (UPDATE) {
      fs.mkdirSync(fixtureDir, { recursive: true });
      for (const [name, bytes] of Object.entries(built)) fs.writeFileSync(path.join(fixtureDir, name), bytes);
      fs.writeFileSync(path.join(fixtureDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    }
    const stale = 'out of date — regenerate with UPDATE_PRINTER_FIXTURES=1 (see the header of this test)';
    expect(JSON.parse(fs.readFileSync(path.join(fixtureDir, 'manifest.json'), 'utf8')), stale).toEqual(manifest);
    for (const [name, bytes] of Object.entries(built)) {
      const pinned = fs.readFileSync(path.join(fixtureDir, name));
      expect(Buffer.from(bytes).equals(pinned), `${name} ${stale}`).toBe(true);
    }
  });
});
