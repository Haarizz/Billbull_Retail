/**
 * CONTRACT — real printer payloads, generated by the real builders, checked by every policy.
 *
 * Each payload BillBull can send to a printer is built here by the code that builds it in
 * production, then checked against the print-agent policy for its own protocol, which must accept
 * it. An ESC/POS receipt must also be refused by the ZPL policy. A ZPL label is plain text to the
 * ESC/POS walker: keeping labels off receipt printers (and receipts off Zebras) is done by the
 * destination's configured protocol in the agent (lib/destinations.js) and by the printer's type in
 * the backend, not by the walkers.
 *
 * The payloads are also pinned as files in billbull-backend/src/test/resources/printer-payloads/,
 * which the backend (PrinterPayloadFixturesTest) and the agent (test/fixtures.test.js) run through
 * their own copies of the policies. So a builder change that would make the backend or the agent
 * refuse a real receipt or label fails one of the three suites before it reaches a till.
 *
 * When a builder changes on purpose, regenerate with:
 *   UPDATE_PRINTER_FIXTURES=1 npx vitest run src/utils/__tests__/printerPayloadFixtures.test.js
 */
const here = path.dirname(fileURLToPath(import.meta.url));
const agentLib = path.resolve(here, '../../../../tools/pos-print-agent/lib');
const fixtureDir = path.resolve(here, '../../../../billbull-backend/src/test/resources/printer-payloads');
const req = createRequire(import.meta.url);
const { inspectEscPos } = req(path.join(agentLib, 'escposPolicy.js'));
const { inspectZpl } = req(path.join(agentLib, 'zplPolicy.js'));
const UPDATE = process.env.UPDATE_PRINTER_FIXTURES === '1';

const utf8 = (s) => new TextEncoder().encode(s);

// A fake canvas whose dithered raster rows spell a drawer pulse, a ZPL format start and a
// ZPL power-cycle: image data that LOOKS like three different commands.
const canvasWithCommandLookalikes = () => {
  const pattern = [0x1b, 0x70, 0x00, 0x19, 0xfa, 0x5e, 0x58, 0x41, 0x7e, 0x4a, 0x52];
  const width = pattern.length * 8;
  const height = 24;
  const data = new Uint8ClampedArray(width * height * 4);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const on = (pattern[x >> 3] >> (7 - (x & 7))) & 1;
      const o = (y * width + x) * 4;
      data[o] = data[o + 1] = data[o + 2] = on ? 0 : 255;
      data[o + 3] = 255;
    }
  }
  return { width, height, getContext: () => ({ getImageData: () => ({ data }) }) };
};

